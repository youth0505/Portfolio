  const attributes = ["aria-label", "title", "placeholder", "content", "alt", "data-project-title"];
  const getLanguage = () => {
    try {
      return localStorage.getItem("site-language") === "zh" ? "zh" : "en";
    } catch (error) {
      return "en";
    }
  };
  let language = getLanguage();

  const translate = (root) => {
    const translateText = (node) => {
      const current = node.nodeValue;
      const text = normalize(current);
      const replacement = (language === "zh" ? translations : reverseTranslations)[text];
      if (replacement) {
        const leading = current.match(/^\s*/)[0];
        const trailing = current.match(/\s*$/)[0];
        node.nodeValue = `${leading}${replacement}${trailing}`;
      }
    };
    if (root.nodeType === Node.TEXT_NODE) translateText(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      translateText(node);
    }

    const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll("*")] : [];
    elements.forEach((element) => {
      attributes.forEach((attribute) => {
        const value = element.getAttribute(attribute);
        const replacement = (language === "zh" ? translations : reverseTranslations)[normalize(value || "")];
        if (replacement) element.setAttribute(attribute, replacement);
      });
    });
  };
